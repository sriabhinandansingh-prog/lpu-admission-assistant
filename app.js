/* ---------- knowledge-base reply ---------- */
function localReply(text) {
  const lang = detectLanguage(text);
  const intent = detectIntent(text);
  const programme = findProgramme(text);

  if (intent === 'greeting' && text.trim().split(/\s+/).length <= 3) return T.greeting[lang];
  if (intent === 'status') return T.status[lang];
  if (intent === 'fees') return T.fees[lang];
  if (intent === 'scholarship') return scholarshipAnswer(lang);
  if (intent === 'hostel') return hostelAnswer(lang);
  if (intent === 'entrance') return entranceAnswer(lang);
  if (intent === 'eligibility') return eligibilityAnswer(programme, lang);
  if (intent === 'admission') return admissionAnswer(lang);
  if (intent === 'placement') return placementAnswer(lang);
  if (intent === 'campus') return campusAnswer(lang);
  if (intent === 'contact') return contactAnswer(lang);
  if (intent === 'programmes') return programmeList(lang);
  if (programme) return programmeDetail(programme, lang);
  return T.fallback[lang];
}

