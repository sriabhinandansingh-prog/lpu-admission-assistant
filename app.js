function detectIntent(text) {
  const t = text.toLowerCase();
  for (const intent of INTENTS) {
    if (intent.kw.some(k => t.includes(k))) return intent.id;
  }
  return 'fallback';
}

function findProgramme(text) {
  if (!KB) return null;
  const t = text.toLowerCase().replace(/[^a-z0-9. ]/g, ' ');
  const alias = {
    btech: ['b.tech', 'btech', 'b tech', 'engineering'],
    bca: ['bca'],
    bba: ['bba'],
    bcom: ['b.com', 'bcom', 'b com'],
    bsc: ['b.sc', 'bsc', 'b sc'],
    ba: ['ba ', ' ba', 'b.a'],
    bdes: ['b.des', 'bdes', 'design'],
    bpharm: ['b.pharm', 'bpharm', 'pharmacy'],
    llb: ['llb', 'law'],
    mba: ['mba'],
    mca: ['mca'],
    mtech: ['m.tech', 'mtech'],
    msc: ['m.sc', 'msc'],
    ma: ['ma ', ' ma', 'm.a'],
    phd: ['phd', 'doctorate'],
    diploma: ['diploma']
  };
  for (const p of KB.programmes) {
    const keys = alias[p.id] || [p.name.toLowerCase()];
    if (keys.some(k => t.includes(k))) return p;
  }
  return null;
}

