/* ---------- settings dialog ---------- */
const dialog = document.getElementById('settingsDialog');
const apiKeyEl = document.getElementById('apiKey');
const endpointEl = document.getElementById('endpoint');
const modelEl = document.getElementById('model');
const modeStatus = document.getElementById('modeStatus');

document.getElementById('settingsBtn').addEventListener('click', () => {
  const s = loadSettings();
  apiKeyEl.value = s.apiKey || '';
  endpointEl.value = s.endpoint || '';
  modelEl.value = s.model || '';
  dialog.showModal();
});

document.getElementById('settingsForm').addEventListener('submit', e => {
  const action = e.submitter ? e.submitter.value : 'cancel';
  if (action !== 'save') return;
  saveSettings({
    apiKey: apiKeyEl.value.trim(),
    endpoint: endpointEl.value.trim(),
    model: modelEl.value.trim()
  });
  updateModeStatus();
});

function updateModeStatus() {
  const s = loadSettings();
  modeStatus.textContent = s.apiKey
    ? 'Model mode. Replies are generated by ' + (s.model || 'your configured model') + '. The key stays in this browser.'
    : 'Knowledge-base mode. Answers come from data/knowledge.json.';
}

/* ---------- boot ---------- */
function greet() {
  const lang = 'en';
  addMessage('bot', T.greeting[lang]);
}

async function boot() {
  try {
    const res = await fetch('data/knowledge.json');
    KB = await res.json();
  } catch (err) {
    addMessage('error', 'Could not load data/knowledge.json. If you opened index.html directly from disk, serve the folder over HTTP instead (for example: python3 -m http.server).');
    return;
  }
  updateModeStatus();
  greet();
}

boot();
