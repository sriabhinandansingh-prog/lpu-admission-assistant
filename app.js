const GOAL_RE = /(admission|दाखिला|ਦਾਖਲਾ|chahiye|lena|lena hai|apply karna)/i;
const DETAIL_RE = /(about|know|details|information|batao|bataiye|jankari|ke baare|बारे|ਬਾਰੇ|eligible|eligib|fee|fees|hostel|placement|scholarship)/i;

function isGoalStatement(text, programme) {
  if (!programme) return false;
  return GOAL_RE.test(text) && !DETAIL_RE.test(text);
}

/* ---------- knowledge-base reply ---------- */
function localReply(text) {
  const lang = detectLanguage(text);
  const intent = detectIntent(text);
  const programme = findProgramme(text);

  if (intent === 'greeting' && text.trim().split(/\s+/).length <= 3) return T.greeting[lang];
  if (intent === 'status') return T.status[lang];
  if (intent === 'fees') return T.fees[lang];
  if (intent === 'scholarship') return scholarshipAnswer(lang);
  if (intent === 'hostel') return hostelAnswer(lang);
  if (intent === 'entrance') return entranceAnswer(lang);
  if (intent === 'eligibility') return eligibilityAnswer(programme, lang);
  if (intent === 'admission') return admissionAnswer(lang);
  if (intent === 'placement') return placementAnswer(lang);
  if (intent === 'campus') return campusAnswer(lang);
  if (intent === 'contact') return contactAnswer(lang);
  if (intent === 'programmes') return programmeList(lang);
  if (programme && isGoalStatement(text, programme)) return followUp(programme, lang);
  if (programme) return programmeDetail(programme, lang);
  return T.fallback[lang];
}

/* ---------- optional model mode ---------- */
function systemPrompt() {
  const compact = KB.programmes.map(p =>
    `${p.name} (${p.level}, ${p.duration}, ${p.school}). Eligibility: ${p.eligibility} Entrance: ${p.entrance}.`
  ).join('\n');
  return [
    'You are the LPU Admission Assistant for Lovely Professional University, Phagwara, Punjab, India.',
    'Reply in the language the student used: English, Hindi, Hinglish or Punjabi.',
    'Answer only from the facts below and from general knowledge of the admission process. Never state a fee, cutoff, deadline or scholarship amount: say you do not have a verified figure and link to https://admission.lpu.in/.',
    'Never guarantee admission, a scholarship or a placement. Never claim to check an application or take a payment.',
    'Format: a direct answer, then key details as short bullets, then the next step, then the official link.',
    'PROGRAMMES:\n' + compact,
    'ADMISSION STEPS: ' + KB.admission_steps.join(' '),
    'SCHOLARSHIPS: ' + KB.scholarships.map(s => s.name).join(', ') + '.',
    'HOSTEL: ' + KB.hostel.join(' ')
  ].join('\n\n');
}

async function backendReply(question, history) {
  const s = loadSettings();
  const base = s.backendUrl.replace(/\/+$/, '');
  const url = /\/functions\/[^/]+$/.test(base) ? base : base + '/api/chat';
  const res = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      question,
      history: history.slice(-8).map(m => ({ role: m.role, content: m.content }))
    })
  });
  if (!res.ok) throw new Error('HTTP ' + res.status);
  const data = await res.json();
  if (!data.answer) throw new Error('No answer in response');
  return data.answer;
}

async function modelReply(history) {
  const s = loadSettings();
  const res = await fetch(s.endpoint || 'https://api.openai.com/v1/chat/completions', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'Authorization': 'Bearer ' + s.apiKey },
    body: JSON.stringify({
      model: s.model || 'gpt-4o-mini',
      temperature: 0.4,
      messages: [{ role: 'system', content: systemPrompt() }].concat(history)
    })
  });
  if (!res.ok) throw new Error('Model request failed (' + res.status + ')');
  const data = await res.json();
  const out = data.choices && data.choices[0] && data.choices[0].message && data.choices[0].message.content;
  if (!out) throw new Error('Empty model response');
  return out.trim();
}

/* ---------- rendering ---------- */
function escapeHtml(str) {
  return str.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function formatMessage(text) {
  let html = escapeHtml(text);
  html = html.replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>');
  html = html.replace(/(https?:\/\/[^\s<]+)/g, '<a href="$1" target="_blank" rel="noopener">$1</a>');
  return html;
}

function addMessage(role, text) {
  const div = document.createElement('div');
  div.className = 'msg ' + (role === 'user' ? 'user' : role === 'error' ? 'bot error' : 'bot');
  div.innerHTML = formatMessage(text);
  messagesEl.appendChild(div);
  messagesEl.scrollTop = messagesEl.scrollHeight;
  return div;
}

function addTyping() {
  const div = document.createElement('div');
  div.className = 'msg bot';
  div.innerHTML = '<span class="typing"><span></span><span></span><span></span></span>';
  messagesEl.appendChild(div);
  messagesEl.scrollTop = messagesEl.scrollHeight;
  return div;
}

/* ---------- conversation ---------- */
const history = [];

async function handleSend(text) {
  const value = (text || '').trim();
  if (!value) return;

  addMessage('user', value);
  history.push({ role: 'user', content: value });
  inputEl.value = '';
  sendBtn.disabled = true;

  const typing = addTyping();
  let reply;
  const s = loadSettings();

  if (s.backendUrl) {
    try {
      reply = await backendReply(value, history);
    } catch (err) {
      reply = 'The backend could not be reached (' + err.message + '). Answering from the built-in knowledge base instead.\n\n' + localReply(value);
    }
  } else if (s.apiKey) {
    try {
      reply = await modelReply(history);
    } catch (err) {
      reply = 'I could not reach the configured model (' + err.message + '). Falling back to the built-in knowledge base.\n\n' + localReply(value);
    }
  } else {
    await new Promise(r => setTimeout(r, 320));
    reply = localReply(value);
  }

  typing.remove();
  addMessage('bot', reply);
  history.push({ role: 'assistant', content: reply });
  sendBtn.disabled = false;
  inputEl.focus();
}

