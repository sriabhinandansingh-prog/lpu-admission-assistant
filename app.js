function updateModeStatus() {
  const s = loadSettings();
  if (s.backendUrl) {
    modeStatus.textContent = 'Backend mode. Answers come from ' + s.backendUrl + ', where the model key is held server-side.';
  } else if (s.apiKey) {
    modeStatus.textContent = 'Local model mode. Replies are generated by ' + (s.model || 'your configured model') + '. The key stays in this browser.';
  } else {
    modeStatus.textContent = 'Knowledge-base mode. Answers come from data/knowledge.json.';
  }
}

