async function modelReply(history) {
  const s = loadSettings();
  const res = await fetch(s.endpoint || 'https://api.openai.com/v1/chat/completions', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'Authorization': 'Bearer ' + s.apiKey },
    body: JSON.stringify({
      model: s.model || 'gpt-4o-mini',
      temperature: 0.4,
      messages: [{ role: 'system', content: systemPrompt() }].concat(history)
    })
  });
  if (!res.ok) throw new Error('Model request failed (' + res.status + ')');
  const data = await res.json();
  const out = data.choices && data.choices[0] && data.choices[0].message && data.choices[0].message.content;
  if (!out) throw new Error('Empty model response');
  return out.trim();
}

/* ---------- rendering ---------- */
function escapeHtml(str) {
  return str.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function formatMessage(text) {
  let html = escapeHtml(text);
  html = html.replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>');
  html = html.replace(/(https?:\/\/[^\s<]+)/g, '<a href="$1" target="_blank" rel="noopener">$1</a>');
  return html;
}

function addMessage(role, text) {
  const div = document.createElement('div');
  div.className = 'msg ' + (role === 'user' ? 'user' : role === 'error' ? 'bot error' : 'bot');
  div.innerHTML = formatMessage(text);
  messagesEl.appendChild(div);
  messagesEl.scrollTop = messagesEl.scrollHeight;
  return div;
}

function addTyping() {
  const div = document.createElement('div');
  div.className = 'msg bot';
  div.innerHTML = '<span class="typing"><span></span><span></span><span></span></span>';
  messagesEl.appendChild(div);
  messagesEl.scrollTop = messagesEl.scrollHeight;
  return div;
}

/* ---------- conversation ---------- */
const history = [];

async function handleSend(text) {
  const value = (text || '').trim();
  if (!value) return;

  addMessage('user', value);
  history.push({ role: 'user', content: value });
  inputEl.value = '';
  sendBtn.disabled = true;

  const typing = addTyping();
  let reply;
  const s = loadSettings();

  if (s.apiKey) {
    try {
      reply = await modelReply(history);
    } catch (err) {
      reply = '**Answer:** I could not reach the configured model (' + err.message + '). Falling back to the built-in knowledge base.\n\n' + localReply(value);
    }
  } else {
    await new Promise(r => setTimeout(r, 320));
    reply = localReply(value);
  }

  typing.remove();
  addMessage('bot', reply);
  history.push({ role: 'assistant', content: reply });
  sendBtn.disabled = false;
  inputEl.focus();
}

